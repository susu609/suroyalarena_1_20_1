package net.susu609.royalarena.arena;

/**
 * Whether the arena dimension is really the mod's arena world, and not
 * something that only has the same name (a datapack that gave
 * {@code royalarena:arena} terrain, a world folder copied from another
 * save, a dimension with someone's builds in it). The mod stamps the
 * dimension's saved data with a random code, the seed of the world it was
 * made in and the mod version; it only builds in, clears, or refreshes a
 * dimension whose stamp it can read and trust.
 */
public final class ArenaWorldCheck {
    private ArenaWorldCheck() {
    }

    /** What the arena dimension's saved data says about it. */
    public record Stamp(String code, long worldSeed, String modVersion,
                        int maxSlot)
    {
    }

    public enum Verdict {
        /** Stamped by this world: go ahead. */
        READY(true),
        /** Empty and unstamped: stamp it now, then go ahead. */
        NEW_STAMP(true),
        /** The server has no arena dimension (the datapack is missing). */
        MISSING(false),
        /** The dimension is not the flat void world the mod defines. */
        NOT_VOID(false),
        /** Stamped, but by another world (a copied folder, another seed). */
        FOREIGN_WORLD(false),
        /** No stamp, and blocks the mod did not put there. */
        UNSTAMPED_BLOCKS(false),
        /** A stamp is there but has no code in it. */
        UNREADABLE_STAMP(false);

        private final boolean usable;

        Verdict(boolean usable) {
            this.usable = usable;
        }

        public boolean usable() {
            return usable;
        }
    }

    /**
     * @param levelExists the server has the dimension
     * @param isVoid      it is generated by the flat generator, all air
     * @param stamp       its saved stamp, or null when it has none
     * @param worldSeed   the seed of this world's overworld
     * @param gridEmpty   no block at any arena slot's floor centre
     */
    public static Verdict check(boolean levelExists, boolean isVoid,
            Stamp stamp, long worldSeed, boolean gridEmpty)
    {
        if (!levelExists)
            return Verdict.MISSING;
        if (!isVoid)
            return Verdict.NOT_VOID;
        if (stamp == null)
            return gridEmpty ? Verdict.NEW_STAMP : Verdict.UNSTAMPED_BLOCKS;
        if (stamp.code() == null || stamp.code().isBlank())
            return Verdict.UNREADABLE_STAMP;
        return stamp.worldSeed() == worldSeed ? Verdict.READY :
                Verdict.FOREIGN_WORLD;
    }

    /** A plain-words reason for a verdict that is not usable. */
    public static String explain(Verdict verdict) {
        return switch (verdict) {
            case MISSING -> "the server has no royalarena:arena dimension " +
                    "(is the mod's datapack loaded?)";
            case NOT_VOID -> "royalarena:arena is not an empty void " +
                    "dimension (another datapack redefined it?)";
            case FOREIGN_WORLD -> "the arena dimension is stamped by another " +
                    "world (a copied world folder?)";
            case UNSTAMPED_BLOCKS -> "the arena dimension has blocks the " +
                    "mod did not build and no stamp";
            case UNREADABLE_STAMP -> "the arena dimension's stamp is empty";
            default -> "ready";
        };
    }
}
