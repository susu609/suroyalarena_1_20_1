package net.susu609.royalarena;

import net.susu609.royalarena.card.BattleCard;
import net.susu609.royalarena.card.CardRole;
import net.susu609.royalarena.card.CostFormula;
import net.susu609.royalarena.card.SpellStats;
import net.susu609.royalarena.card.TroopStats;
import net.susu609.royalarena.card.TroopTraits;
import net.susu609.royalarena.stats.Json;
import net.susu609.royalarena.tower.TowerKind;

import java.io.IOException;
import java.nio.file.Files;
import java.nio.file.Path;
import java.time.OffsetDateTime;
import java.time.ZoneOffset;
import java.time.format.DateTimeFormatter;
import java.util.ArrayList;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Locale;
import java.util.Map;

/**
 * Card statistics for the phone-friendly page in {@code docs/stats/}
 * ({@code gradlew statsReport}): every card's stats straight from the code,
 * what {@link Sim} measures (pushes, walking alone to the tower), the bot
 * matches of {@link BalanceReport}, and the push matrix. Writes
 * {@code docs/stats/data/stats.js} (loaded by the page, so it also opens
 * from a file) and {@code stats.json}, and adds one line per run to
 * {@code history.jsonl} so the page can show how cards changed.
 *
 * <p>Arguments: number of bot matches (default 200), output folder.</p>
 */
public final class StatsReport {
    /** Runs kept in the history (the same commit replaces its old run). */
    private static final int HISTORY = 60;
    private static final Path PORTRAITS = Path.of(
            "src/main/resources/assets/royalarena/textures/gui/card");

    private StatsReport() {
    }

    public static void main(String[] args) throws IOException {
        int matches = args.length > 0 ? Integer.parseInt(args[0]) : 200;
        Path dir = Path.of(args.length > 1 ? args[1] : "docs/stats/data");
        long started = System.currentTimeMillis();

        BalanceReport.Result bots = BalanceReport.play(matches);
        List<BattleCard> attackers = new ArrayList<>();
        List<BattleCard> defenders = new ArrayList<>();
        for (BattleCard card : BattleCard.values()) {
            if (card.isSpell())
                continue;
            attackers.add(card);
            if (!card.stats().traits().buildingsOnly())
                defenders.add(card);
        }
        double[][] push = new double[attackers.size()][defenders.size()];
        for (int a = 0; a < attackers.size(); a++) {
            for (int d = 0; d < defenders.size(); d++)
                push[a][d] = Sim.push(attackers.get(a), defenders.get(d));
        }

        String commit = commit();
        String date = OffsetDateTime.now(ZoneOffset.UTC).format(
                DateTimeFormatter.ISO_OFFSET_DATE_TIME);
        Map<String, Object> root = new LinkedHashMap<>();
        root.put("meta", meta(commit, date, matches));
        List<Object> cards = new ArrayList<>();
        Map<String, Object> history = new LinkedHashMap<>();
        for (BattleCard card : BattleCard.values()) {
            Map<String, Object> c = card(card, bots.cards.get(card),
                    attackers, defenders, push);
            cards.add(c);
            Map<String, Object> h = new LinkedHashMap<>();
            h.put("cost", card.cost());
            h.put("winrate", ((Map<?, ?>) c.get("bot")).get("winrate"));
            Object fight = c.get("fight");
            h.put("score", fight instanceof Map<?, ?> f ? f.get("score") :
                    null);
            history.put(card.id(), h);
        }
        root.put("cards", cards);
        root.put("matchups", matchups(attackers, defenders, push));
        root.put("matches", matches(bots));

        Map<String, Object> run = new LinkedHashMap<>();
        run.put("commit", commit);
        run.put("date", date);
        run.put("matches", matches);
        run.put("cards", history);
        List<String> lines = history(dir.resolve("history.jsonl"), commit,
                Json.write(run));
        root.put("history", new Json.Raw("[" + String.join(",", lines) +
                "]"));

        Files.createDirectories(dir);
        String json = Json.write(root);
        Files.writeString(dir.resolve("stats.json"), json + "\n");
        Files.writeString(dir.resolve("stats.js"),
                "// Generated by gradlew statsReport; do not edit.\n" +
                        "window.ROYAL_STATS = " + json + ";\n");
        Files.writeString(dir.resolve("history.jsonl"),
                String.join("\n", lines) + "\n");
        System.out.printf(Locale.ROOT, "Stats for %d cards, %d bot matches, " +
                        "%d runs of history, %d s.%nWritten to %s%n",
                cards.size(), matches, lines.size(),
                (System.currentTimeMillis() - started) / 1000L,
                dir.toAbsolutePath());
    }

    private static Map<String, Object> meta(String commit, String date,
            int matches)
    {
        Map<String, Object> m = new LinkedHashMap<>();
        m.put("commit", commit);
        m.put("date", date);
        m.put("botMatches", matches);
        m.put("towerDps", round(princessDps(), 2));
        m.put("towerHealth", TowerKind.PRINCESS.maxHealth());
        m.put("towerHpPerElixir", Sim.TOWER_HP_PER_ELIXIR);
        Map<String, Object> band = new LinkedHashMap<>();
        band.put("minScore", PowerCreepTest.MIN_SCORE);
        band.put("maxScore", PowerCreepTest.MAX_SCORE);
        band.put("minSiege", PowerCreepTest.MIN_SIEGE);
        band.put("maxSiege", PowerCreepTest.MAX_SIEGE);
        band.put("minSpell", PowerCreepTest.MIN_SPELL);
        band.put("maxSpell", PowerCreepTest.MAX_SPELL);
        m.put("band", band);
        return m;
    }

    private static double princessDps() {
        return TowerKind.PRINCESS.damage() /
                (TowerKind.PRINCESS.attackTicks() / 20.0D);
    }

    private static Map<String, Object> card(BattleCard card,
            BalanceReport.Tally tally, List<BattleCard> attackers,
            List<BattleCard> defenders, double[][] push)
    {
        Map<String, Object> c = new LinkedHashMap<>();
        c.put("id", card.id());
        c.put("name", card.displayName());
        c.put("cost", card.cost());
        c.put("kind", card.isSpell() ? "spell" : "troop");
        List<Object> roles = new ArrayList<>();
        for (CardRole role : CardRole.of(card))
            roles.add(role.name().toLowerCase(Locale.ROOT));
        c.put("roles", roles);
        c.put("portrait", Files.exists(PORTRAITS.resolve(card.id() + ".png"))
                ? card.id() + ".png" : null);
        if (card.isSpell())
            c.put("spell", spell(card));
        else
            troop(card, c, attackers, defenders, push);
        Map<String, Object> bot = new LinkedHashMap<>();
        bot.put("decks", tally.games);
        bot.put("winrate", tally.games == 0 ? null : round(tally.rate(), 4));
        bot.put("margin", tally.games == 0 ? null : round(tally.margin(), 4));
        bot.put("playsPerGame", tally.games == 0 ? null :
                round(tally.plays / (double) tally.games, 2));
        c.put("bot", bot);
        return c;
    }

    private static void troop(BattleCard card, Map<String, Object> c,
            List<BattleCard> attackers, List<BattleCard> defenders,
            double[][] push)
    {
        TroopStats s = card.stats();
        TroopTraits t = s.traits();
        double body = CardRole.bodyHealth(s) * s.count();
        double dps = s.damage() / (s.attackTicks() / 20.0D) * s.count();
        Map<String, Object> u = new LinkedHashMap<>();
        u.put("count", s.count());
        u.put("health", s.health());
        u.put("totalHealth", round(body, 1));
        u.put("damage", s.damage());
        u.put("interval", round(s.attackTicks() / 20.0D, 2));
        u.put("dps", round(dps, 2));
        u.put("range", s.range());
        u.put("speed", s.speed());
        u.put("modelScale", round(card.modelScale(), 2));
        u.put("rawCost", round(CostFormula.raw(s), 2));
        u.put("dpsPerElixir", round(dps / card.cost(), 2));
        u.put("healthPerElixir", round(body / card.cost(), 1));
        // Seconds the whole card survives a Princess tower alone.
        u.put("tankSeconds", round(body / princessDps(), 1));
        Map<String, Object> traits = new LinkedHashMap<>();
        traits.put("splash", t.splashRadius());
        traits.put("selfDestruct", t.selfDestruct());
        traits.put("knockback", t.knockback());
        traits.put("buildingsOnly", t.buildingsOnly());
        traits.put("slowSeconds", round(t.slowTicks() / 20.0D, 2));
        traits.put("splits", s.split() == null ? 0 : s.split().generations());
        traits.put("weapon", card.heldItemId() == null ? null :
                card.heldItemId().replace("minecraft:", ""));
        u.put("traits", traits);
        c.put("troop", u);

        Sim.Solo solo = Sim.solo(card);
        Map<String, Object> alone = new LinkedHashMap<>();
        alone.put("reachSeconds", solo.reachSeconds() < 0 ? null :
                round(solo.reachSeconds(), 1));
        alone.put("healthOnArrival", round(solo.healthOnArrival(), 3));
        alone.put("towerDamage", solo.towerDamage());
        alone.put("towerDamagePerElixir",
                round(solo.towerDamage() / (double) card.cost(), 1));
        alone.put("fallSeconds", solo.fallSeconds() < 0 ? null :
                round(solo.fallSeconds(), 1));
        c.put("solo", alone);

        int row = attackers.indexOf(card);
        double attack = 0.0D;
        for (double value : push[row])
            attack += value;
        attack /= defenders.size();
        Map<String, Object> fight = new LinkedHashMap<>();
        fight.put("attack", round(attack, 2));
        int column = defenders.indexOf(card);
        if (column < 0) {
            fight.put("defend", null);
            fight.put("score", null);
        } else {
            // As PowerCreepTest: against the troops that fight.
            double defend = 0.0D;
            int fights = 0;
            for (int a = 0; a < attackers.size(); a++) {
                if (defenders.contains(attackers.get(a))) {
                    defend -= push[a][column];
                    fights++;
                }
            }
            defend /= fights;
            fight.put("defend", round(defend, 2));
            fight.put("score", round((attack + defend) / 2.0D, 2));
        }
        c.put("fight", fight);
    }

    private static Map<String, Object> spell(BattleCard card) {
        SpellStats s = card.spell();
        Map<String, Object> m = new LinkedHashMap<>();
        m.put("radius", s.radius());
        m.put("castSeconds", round(s.castTicks() / 20.0D, 2));
        m.put("pulses", s.pulses());
        m.put("durationSeconds", round(s.durationTicks() / 20.0D, 2));
        m.put("perTarget", round(s.damagePerTarget(), 1));
        m.put("heal", s.heal());
        m.put("towerShare", s.towerMultiplier());
        m.put("maxTargets", s.maxTargets());
        m.put("stunSeconds", round(s.stunTicks() / 20.0D, 2));
        m.put("freezeSeconds", round(s.freezeTicks() / 20.0D, 2));
        m.put("knockback", s.knockback());
        m.put("burnSeconds", round(s.burnTicks() / 20.0D, 2));
        m.put("rawCost", round(CostFormula.raw(s), 2));
        m.put("valuePerElixir", round(CostFormula.raw(s) / card.cost(), 3));
        return m;
    }

    private static Map<String, Object> matchups(List<BattleCard> attackers,
            List<BattleCard> defenders, double[][] push)
    {
        Map<String, Object> m = new LinkedHashMap<>();
        m.put("attackers", attackers.stream().map(BattleCard::id).toList());
        m.put("defenders", defenders.stream().map(BattleCard::id).toList());
        List<Object> rows = new ArrayList<>();
        for (double[] row : push) {
            List<Object> values = new ArrayList<>();
            for (double v : row)
                values.add(round(v, 2));
            rows.add(values);
        }
        m.put("values", rows);
        return m;
    }

    private static Map<String, Object> matches(BalanceReport.Result r) {
        Map<String, Object> m = new LinkedHashMap<>();
        m.put("count", r.matches);
        m.put("blueWins", r.blueWins);
        m.put("redWins", r.redWins());
        m.put("draws", r.draws);
        m.put("averageSeconds", round(r.averageSeconds(), 1));
        m.put("overtimes", r.overtimes);
        m.put("kingFalls", r.kings);
        return m;
    }

    /** The old runs without this commit's, plus this run, newest last. */
    private static List<String> history(Path file, String commit,
            String line) throws IOException
    {
        List<String> lines = new ArrayList<>();
        if (Files.exists(file)) {
            String mark = "\"commit\":" + Json.quote(commit) + ",";
            for (String old : Files.readAllLines(file)) {
                if (!old.isBlank() && !old.startsWith("{" + mark))
                    lines.add(old.trim());
            }
        }
        lines.add(line);
        while (lines.size() > HISTORY)
            lines.remove(0);
        return lines;
    }

    /** Short commit id, "+" when there are uncommitted changes. */
    private static String commit() {
        try {
            Process p = new ProcessBuilder("git", "describe", "--always",
                    "--dirty=+").redirectErrorStream(true).start();
            String out = new String(p.getInputStream().readAllBytes()).trim();
            return p.waitFor() == 0 && !out.isEmpty() ? out : "local";
        } catch (IOException | InterruptedException e) {
            return "local";
        }
    }

    private static double round(double value, int places) {
        double scale = Math.pow(10.0D, places);
        return Math.round(value * scale) / scale;
    }
}
